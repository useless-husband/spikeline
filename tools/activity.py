#!/usr/bin/env python3
"""Switching activity from simulation -- a RELATIVE proxy, not a power number.

There is no open-source power sign-off flow for this design, so no milliwatt
figure is given anywhere in this project.  What simulation can show is how
often signals change: dynamic power in CMOS grows with the number of
transitions (times capacitance and voltage squared, which are unknown here).

The chip is built with Verilator's toggle coverage (build/vsim_cov), run in
real time (spike detection and compression in parallel, 0.1 s, 96 channels)
with each PE clocked near its minimum, and every 0->1 and 1->0 transition of
every signal bit is counted and grouped by block.  Clock edges per sample
are listed separately: clock-tree power, which toggle counts do not include,
scales with them.

    python3 tools/activity.py   -> docs/results/activity.md
"""

from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(REPO / "model"), str(REPO / "tests" / "system")]

import chip as C  # noqa: E402
import synthdata as S  # noqa: E402

PE_NAMES = ["band-pass", "noise", "NEO", "snippet", "predictor", "Rice"]
CLOCKS = {"fab": 10.0, "bp": 40.0, "noise": 5.0, "neo": 5.0, "snip": 8.0, "pred": 3.2, "rice": 3.6}  # as tools/bench.py
FRAMES = 3000


def group(h):
    m = re.search(r"g_tile\[(\d)\]\.u_tile(.*)", h)
    if m:
        p = int(m.group(1))
        return f"{PE_NAMES[p]} PE" if ".g_pe.u_pe" in m.group(2) else f"{PE_NAMES[p]} tile boundary (FIFOs, crossings)"
    if "u_xbar" in h:
        return "crossbar"
    return "ports, registers, counters"


def main():
    x = S.make_recording(FRAMES / 30000, snr=5, seed=2001)["x"][:FRAMES]
    d = C.BUILD / "sysrun" / "activity"
    s = C.Script().drain().routes(C.BOTH).feed(FRAMES).drain()
    res = C.run("activity", s, x, variant="cov", adc_period=347222, seed=1,
                periods={k: int(round(1e6 / v)) for k, v in CLOCKS.items()}, coverage=d / "cov.dat")
    assert res.stats["overruns"] == 0, "the chip fell behind; clocks too low for real time"
    toggles = Counter()
    for line in open(d / "cov.dat", encoding="latin-1"):
        if not line.startswith("C '") or "v_toggle" not in line:
            continue
        key, count = line.rsplit(" ", 1)
        h = re.search(r"\x01h\x02([^\x01']*)", key).group(1)
        toggles[group(h)] += int(count)
    samples = x.size
    total = sum(toggles.values())
    secs = FRAMES / 30000
    out = ["# Switching activity (relative proxy, not power)", "",
           "Generated by `make activity` (tools/activity.py).  **These are counts of signal transitions in "
           "simulation, not a power measurement.**  No open-source tool here can turn them into milliwatts; "
           "they only say which blocks switch more than others.", "",
           f"Run: spike detection and compression in parallel, {FRAMES} frames ({secs * 1000:.0f} ms) of a "
           "synthetic recording (SNR 5) at real time, no overruns.  Clocks: "
           + ", ".join(f"{k} {v:g} MHz" for k, v in CLOCKS.items()) + ".", "",
           "| Block | transitions per input sample | share |", "|---|---:|---:|"]
    for k, v in sorted(toggles.items(), key=lambda kv: -kv[1]):
        out.append(f"| {k} | {v / samples:.1f} | {100 * v / total:.1f}% |")
    out += [f"| **total** | {total / samples:.1f} | 100% |", "",
            "Clock edges per input sample (rising edges; clock-tree power scales with these):", "",
            "| Clock | MHz | edges per sample |", "|---|---:|---:|"]
    for k, v in CLOCKS.items():
        out.append(f"| {k} | {v:g} | {v * 1e6 / (96 * 30000):.2f} |")
    out.append("")
    path = REPO / "docs" / "results" / "activity.md"
    path.write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
