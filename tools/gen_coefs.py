#!/usr/bin/env python3
"""Design the 300-6000 Hz band-pass filter and quantise its coefficients.

The filter is a 4th-order Butterworth band-pass at fs = 30 kHz, split into
two second-order sections (biquads).  scipy returns the low-pass section
first; we run the high-pass section first so that the electrode offset and
the large low-frequency field potential are removed before the second
section, which keeps the intermediate signal small.

Coefficients become signed 18-bit integers with 16 fractional bits (Q2.16,
range [-2, 2)), the width of one DSP48E1 multiplier input.  The feedback
coefficients are stored negated (-a1, -a2) so the hardware only adds.

Writes two files that must agree, so both come from here:
    rtl/bandpass_coefs.svh   localparams included by rtl/pe_bandpass.sv
    model/sl_coefs.py        the same integers for the golden model

Run from the repository root:  python3 tools/gen_coefs.py
"""

from pathlib import Path

from scipy.signal import butter

FS_HZ = 30000
BAND_HZ = (300, 6000)
CF = 16  # coefficient fractional bits
COEF_W = 18

REPO = Path(__file__).resolve().parents[1]


def design():
    sos = butter(2, BAND_HZ, btype="bandpass", fs=FS_HZ, output="sos")
    hp = sos[[i for i in range(len(sos)) if abs(sos[i][1] + 2 * sos[i][0]) < 1e-9][0]]
    lp = sos[[i for i in range(len(sos)) if abs(sos[i][1] + 2 * sos[i][0]) >= 1e-9][0]]
    return [hp, lp]


def quantise(sections, cf=CF, width=COEF_W):
    lo, hi = -(1 << (width - 1)), (1 << (width - 1)) - 1
    out = []
    for s in sections:
        b0, b1, b2, _a0, a1, a2 = s
        vals = [b0, b1, b2, -a1, -a2]
        q = [max(lo, min(hi, round(v * (1 << cf)))) for v in vals]
        out.append(q)
    return out


def main() -> None:
    q = quantise(design())
    names = ["B0", "B1", "B2", "NA1", "NA2"]
    svh = ["// Generated by tools/gen_coefs.py -- do not edit.",
           f"// 4th-order Butterworth band-pass {BAND_HZ[0]}-{BAND_HZ[1]} Hz at {FS_HZ} Hz as two biquads,",
           f"// signed {COEF_W}-bit, {CF} fractional bits.  Section 0 = high-pass, section 1 = low-pass.",
           "// NA1/NA2 are the negated feedback coefficients (-a1, -a2)."]
    py = ['"""Generated by tools/gen_coefs.py -- do not edit."""', "",
          f"CF = {CF}", f"COEF_W = {COEF_W}",
          "# per section: b0, b1, b2, -a1, -a2 (section 0 = high-pass, 1 = low-pass)",
          "SECTIONS = ["]
    for i, sec in enumerate(q):
        for n, v in zip(names, sec):
            lit = f"{COEF_W}'sh{v & ((1 << COEF_W) - 1):05x}"  # two's complement
            svh.append(f"localparam logic signed [{COEF_W - 1}:0] S{i}_{n} = {lit};  // {v}")
        py.append(f"    ({', '.join(str(v) for v in sec)}),")
    py.append("]")
    (REPO / "rtl" / "bandpass_coefs.svh").write_text("\n".join(svh) + "\n")
    (REPO / "model" / "sl_coefs.py").write_text("\n".join(py) + "\n")
    print("wrote rtl/bandpass_coefs.svh and model/sl_coefs.py")
    for i, sec in enumerate(q):
        print(f"section {i}: {sec}")


if __name__ == "__main__":
    main()
