#!/usr/bin/env python3
"""Fixed-point analysis of the band-pass filter: what coefficient and state
precision cost, measured.

For each (coefficient fractional bits CF, state fractional bits FS) the same
direct-form-I cascade as rtl/pe_bandpass.sv is run on a synthetic recording
and compared with the double-precision filter (scipy sosfilt):
  * output error, in LSB rms (rounding the output alone gives 0.289),
  * the largest deviation of the quantised coefficients' frequency response
    from the ideal one inside 300-6000 Hz (dB),
  * the high-pass section's pole radius (closest to the unit circle),
  * spike-detection F1 at SNR 5 with the chip's other PEs unchanged.
The chip uses CF = 16, FS = 6 (checked here to equal model/slmodel.py).

    python3 tools/quant_analysis.py   -> docs/results/quantisation.md
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from scipy.signal import butter, freqz, sosfilt

REPO = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(REPO / "model"), str(REPO / "tools")]

import slmodel as M  # noqa: E402
import synthdata as S  # noqa: E402
from gen_coefs import design, quantise  # noqa: E402
from metrics import prf, score  # noqa: E402


def fixed_filter(x, cf, fs):
    """rtl/pe_bandpass.sv with CF coefficient and FS state fractional bits."""
    q = quantise(design(), cf=cf, width=cf + 2)
    sw = 18 + fs
    (b00, b01, b02, n01, n02), (b10, b11, b12, n11, n12) = q
    nch = x.shape[1]
    x1 = np.zeros(nch, np.int64)
    x2, y1a, y2a, y1b, y2b = (np.zeros(nch, np.int64) for _ in range(5))
    hc = 1 << (cf - 1)
    hs = (1 << (fs - 1)) if fs else 0
    y = np.empty_like(x)
    for f in range(len(x)):
        acc = b00 * (x[f] << fs) + b01 * (x1 << fs) + b02 * (x2 << fs) + n01 * y1a + n02 * y2a
        v0 = M.sat((acc + hc) >> cf, sw)
        acc = b10 * v0 + b11 * y1a + b12 * y2a + n11 * y1b + n12 * y2b
        v1 = M.sat((acc + hc) >> cf, sw)
        y[f] = M.sat((v1 + hs) >> fs, 16)
        x2, x1 = x1, x[f]
        y2a, y1a = y1a, v0
        y2b, y1b = y1b, v1
    return y


def response_error_db(cf):
    """Largest response error in the pass band (dB) and largest pole radius."""
    q = np.array(quantise(design(), cf=cf, width=cf + 2), dtype=float) / (1 << cf)
    sos_q = np.array([[b0, b1, b2, 1.0, -na1, -na2] for b0, b1, b2, na1, na2 in q])
    f = np.linspace(300, 6000, 400)
    _, hi = freqz_sos(np.array(design()), f)
    _, hq = freqz_sos(sos_q, f)
    pole_r = max(np.abs(np.roots([1.0, -row[3], -row[4]])).max() for row in q)
    return float(np.max(np.abs(20 * np.log10(np.abs(hq) / np.abs(hi))))), pole_r


def freqz_sos(sos, f):
    h = np.ones(len(f), dtype=complex)
    for s in sos:
        _, hs = freqz(s[:3], s[3:], worN=f, fs=30000)
        h *= hs
    return f, h


def main():
    rec = S.make_recording(1.0, snr=5, seed=2001)
    x8 = rec["x"][:, :8].astype(np.int64)
    ref = sosfilt(butter(2, (300, 6000), btype="bandpass", fs=30000, output="sos"), x8.astype(float), axis=0)
    assert np.array_equal(fixed_filter(x8, 16, 6), M.Bandpass(8).run(x8)), "analysis filter != model"
    ideal_r = max(np.abs(np.roots([1.0, s[4], s[5]])).max() for s in design())

    out = ["# Band-pass filter fixed-point analysis", "",
           "Generated by `make quant` (tools/quant_analysis.py).  Recording: seed 2001, SNR 5, 1 s; "
           "error measured on 8 channels against double-precision `scipy.signal.sosfilt`.", "",
           f"Ideal largest pole radius: {ideal_r:.6f} (high-pass section; 1.0 would be unstable).", "",
           "## Output error (LSB rms) versus coefficient and state precision", "",
           "| coefficient frac. bits CF | response error 300-6000 Hz (dB) | pole radius | FS=0 | FS=2 | FS=4 | FS=6 | FS=8 |",
           "|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for cf in (8, 10, 12, 14, 16):
        db, pr = response_error_db(cf)
        errs = []
        for fs in (0, 2, 4, 6, 8):
            e = fixed_filter(x8, cf, fs) - ref
            errs.append(f"{e.std():.3f}")
        mark = " (chip)" if cf == 16 else ""
        out.append(f"| {cf}{mark} | {db:.3f} | {pr:.6f} | " + " | ".join(errs) + " |")
    out += ["", "The chip's choice is CF = 16, FS = 6: 0.33 LSB rms, of which 0.29 is the unavoidable "
            "rounding of the output to whole LSBs.", ""]

    # end-to-end: does the filter precision change detection?
    x = rec["x"].astype(np.int64)
    out += ["## Effect on spike detection (SNR 5, 96 channels, 1 s, energy mode, default threshold)", "",
            "| filter | precision | recall | F1 |", "|---|---:|---:|---:|"]
    variants = [("double precision (rounded to 16-bit for the next PE)",
                 np.clip(np.round(sosfilt(butter(2, (300, 6000), btype="bandpass", fs=30000, output="sos"),
                                          x.astype(float), axis=0)), -32768, 32767).astype(np.int64)),
                ("chip: CF 16, FS 6", M.Bandpass().run(x)),
                ("CF 10, FS 0", fixed_filter(x, 10, 0)),
                ("CF 8, FS 0", fixed_filter(x, 8, 0))]
    for name, y in variants:
        noise, ready = M.Noise().run(y)
        xd, det = M.Neo().run(y, noise, ready)
        p, r, f = prf(*score(rec, M.Snippet().run(xd, det)))
        out.append(f"| {name} | {p:.3f} | {r:.3f} | {f:.3f} |")
    out.append("")
    path = REPO / "docs" / "results" / "quantisation.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
