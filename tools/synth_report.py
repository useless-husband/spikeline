#!/usr/bin/env python3
"""Turn Yosys `stat -json` files into synth/report.md.

    synth_report.py build/synth [--check]

Reads build/synth/<pe>.json for each PE synthesised on its own and
build/synth/spikeline_top.json for the whole chip.  --check exits non-zero
if the chip does not fit the XC7S50."""

import json
import re
import sys
from collections import Counter
from pathlib import Path

# Spartan-7 XC7S50 (DS180): 32,600 LUTs, 65,200 flip-flops, 75 x 36 Kb block RAM, 120 DSP48E1
CAPACITY = {"LUT": 32600, "FF": 65200, "BRAM36": 75, "DSP": 120}
PES = [("pe_bandpass", "band-pass filter (2 biquads, 1 multiplier)"),
       ("pe_noise", "noise estimator (median tracker)"),
       ("pe_neo", "NEO / amplitude detector"),
       ("pe_snippet", "snippet extractor (incl. ring buffer)"),
       ("pe_predict", "linear predictor"),
       ("pe_rice", "adaptive Rice coder + bit packer")]


def resolve(mods, t):
    for k in (t, "\\" + t):
        if k in mods:
            return k
    return None


def totals(mods, name, memo):
    if name in memo:
        return memo[name]
    c = Counter()
    for t, n in mods[name]["num_cells_by_type"].items():
        sub = resolve(mods, t)
        if sub:
            for k, v in totals(mods, sub, memo).items():
                c[k] += n * v
        else:
            c[t] += n
    memo[name] = c
    return c


def base(name):
    name = re.sub(r"^\\?\$paramod\$?[0-9a-f]*\\", "", name.lstrip("\\"))
    return name.split("\\")[0]


def own_cells(mods, name, mult, acc):
    """Accumulate each module's own leaf cells (not its submodules') by base name."""
    leaf = Counter()
    for t, n in mods[name]["num_cells_by_type"].items():
        sub = resolve(mods, t)
        if sub:
            own_cells(mods, sub, mult * n, acc)
        else:
            leaf[t] += n * mult
    acc.setdefault(base(name), Counter()).update(leaf)


def classify(c):
    lut = sum(v for k, v in c.items() if re.fullmatch(r"LUT[1-6]|INV", k))
    lutram = sum(v for k, v in c.items() if re.fullmatch(r"RAM(32|64|128|256)[A-Z0-9]*", k))
    ff = sum(v for k, v in c.items() if re.fullmatch(r"FD[A-Z]*", k))
    bram = c["RAMB36E1"] + c["RAMB18E1"] / 2
    return {"LUT": lut, "LUTRAM": lutram, "FF": ff, "BRAM36": bram, "DSP": c["DSP48E1"],
            "CARRY4": c["CARRY4"]}


def load(path, top):
    d = json.load(open(path))
    mods = d["modules"]
    return d, classify(totals(mods, resolve(mods, top), {}))


def fmt(v):
    return f"{v:g}" if isinstance(v, float) else f"{v:,}"


def main():
    d = Path(sys.argv[1])
    ver = "Yosys"
    out = ["# Synthesis report (Yosys `synth_xilinx`, Spartan-7 XC7S50)", "",
           "Generated by `make synth`.  Each PE is synthesised on its own (NCH = 96), then the whole chip "
           "(`spikeline_top`, every PE in its own clock domain).  LUTRAM = distributed RAM primitives "
           "(the per-channel state memories and FIFO storage).", "",
           "| Block | LUT | LUTRAM | FF | BRAM36 | DSP48E1 | CARRY4 |", "|---|---:|---:|---:|---:|---:|---:|"]
    pe_sum = Counter()
    for name, desc in PES:
        meta, r = load(d / f"{name}.json", name)
        ver = meta.get("creator", ver).split("(")[0].strip()
        pe_sum.update(r)
        out.append(f"| {desc} | " + " | ".join(fmt(r[k]) for k in ("LUT", "LUTRAM", "FF", "BRAM36", "DSP", "CARRY4")) + " |")
    out.append("| **six PEs** | " + " | ".join(fmt(pe_sum[k]) for k in ("LUT", "LUTRAM", "FF", "BRAM36", "DSP", "CARRY4")) + " |")
    _, chip = load(d / "spikeline_top.json", "spikeline_top")
    out.append("| **whole chip** (PEs + async FIFOs + crossbar + registers) | " +
               " | ".join(fmt(chip[k]) for k in ("LUT", "LUTRAM", "FF", "BRAM36", "DSP", "CARRY4")) + " |")
    d_chip = json.load(open(d / "spikeline_top.json"))["modules"]
    acc = {}
    own_cells(d_chip, resolve(d_chip, "spikeline_top"), 1, acc)
    names = {"sl_xbar": "crossbar (7 sources x 9 destinations, 41-bit)",
             "sl_async_fifo": "async FIFOs (12 x 8 entries)", "sl_fifo": "port FIFOs (4 x 16 entries)",
             "sl_cfg_cdc": "config crossings (6)", "sl_sync2": "two-flop synchronisers",
             "sl_tile": "tile glue (idle detection)", "spikeline_top": "registers and counters",
             "sl_rst_sync": "reset synchronisers"}
    out += ["", "Where the rest of the whole chip goes (leaf cells by module):", "",
            "| Part | LUT | LUTRAM | FF |", "|---|---:|---:|---:|"]
    for k, label in names.items():
        if k in acc:
            r = classify(acc[k])
            out.append(f"| {label} | {fmt(r['LUT'])} | {fmt(r['LUTRAM'])} | {fmt(r['FF'])} |")
    out += ["", "| Resource | Whole chip | XC7S50 | Share |", "|---|---:|---:|---:|"]
    fits = True
    for k, name in (("LUT", "LUT (logic)"), ("FF", "Flip-flops"), ("BRAM36", "Block RAM (36 Kb)"), ("DSP", "DSP48E1")):
        used = chip[k] + (chip["LUTRAM"] if k == "LUT" else 0)
        share = used / CAPACITY[k]
        fits &= share <= 1
        label = "LUT (logic + LUTRAM)" if k == "LUT" else name
        out.append(f"| {label} | {fmt(used)} | {CAPACITY[k]:,} | {100 * share:.1f}% |")
    out += ["", f"Tool: {ver}.  No timing numbers: Yosys maps to 7-series cells but does not place, route "
            "or time them, and the design has not been run on a board.", ""]
    Path("synth/report.md").write_text("\n".join(out))
    print("\n".join(out))
    if "--check" in sys.argv and not fits:
        sys.exit("does not fit the XC7S50")


if __name__ == "__main__":
    main()
